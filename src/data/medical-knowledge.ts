/**
 * دالة التحليل والتصنيف الدقيق لقراءة ضغط الدم وفق إرشادات AHA/ACC المعتمدة
 */
export function classifyBloodPressure(systolic: number, diastolic: number): BloodPressureCategory {
  if (systolic <= 0 || diastolic <= 0 || isNaN(systolic) || isNaN(diastolic)) {
    return BP_CATEGORIES[0];
  }

  // أزمة طارئة: انقباضي > 180 أو انبساطي > 120
  if (systolic > 180 || diastolic > 120) {
    return BP_CATEGORIES[4];
  }

  // مرحلة ثانية: انقباضي ≥ 140 أو انبساطي ≥ 90
  if (systolic >= 140 || diastolic >= 90) {
    return BP_CATEGORIES[3];
  }

  // مرحلة أولى: انقباضي 130-139 أو انبساطي 80-89
  if ((systolic >= 130 && systolic <= 139) || (diastolic >= 80 && diastolic <= 89)) {
    return BP_CATEGORIES[2];
  }

  // مرتفع: انقباضي 120-129 مع انبساطي أقل من 80
  if (systolic >= 120 && systolic <= 129 && diastolic < 80) {
    return BP_CATEGORIES[1];
  }

  // طبيعي: انقباضي < 120 و انبساطي < 80
  return BP_CATEGORIES[0];
}

